fine_lons = np.linspace(-180, 180, 361)
contours_output = []

for cid, cinfo in GLE77_SPECS.items():
    knots = np.array(cinfo['knots'])
    kx = knots[:, 0]
    ky = knots[:, 1]
    
    # Smooth cubic-style interpolation
    fine_y = np.interp(fine_lons, kx, ky)
    
    # Moving average filter for organic curves
    ksize = 9
    kernel = np.ones(ksize) / ksize
    pad_y = np.pad(fine_y, ksize // 2, mode='edge')
    smooth_y = np.convolve(pad_y, kernel, mode='valid')
    
    pts = [{'lon': round(float(lo), 2), 'lat': round(float(la), 2)} for lo, la in zip(fine_lons, smooth_y)]
    hem = 'north' if 'north' in cid else 'south'
    
    contours_output.append({
        'id': cid,
        'rc': cinfo['rc'],
        'label': str(cinfo['rc']),
        'hemisphere': hem,
        'color': cinfo['color'],
        'points': pts,
        'labelPos': {'lon': cinfo['labelPos'][0], 'lat': cinfo['labelPos'][1]}
    })

# Add 17 GV closed loop around Southeast Asia (Doi Inthanon, Thailand, Bay of Bengal)
